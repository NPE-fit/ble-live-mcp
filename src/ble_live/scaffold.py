def _table_for(category: str, language: str) -> str:
    fmt = _FORMATS[language]["row"]
    lines = []
    for index, name, size, signed in _rows(category):
        lines.append(
            fmt.format(
                index=index,
                name=name.replace('"', "'"),
                size=size,
                signed=signed,
                signed_c="true" if signed else "false",
                signed_cs="true" if signed else "false",
            )
        )
    return "\n".join(lines)


def scaffold(language: str) -> dict[str, str]:
    """Return {'filename': ..., 'language': ..., 'source': ...} for one language."""
    if language not in LANGUAGES:
        raise ValueError(f"language is one of {LANGUAGES}")
    comment = _FORMATS[language]["comment"]
    text = _TEMPLATES[language]
    text = text.replace("@@VERSION@@", spec.version())
    text = text.replace("@@QUIRKS@@", _quirk_lines(comment))
    text = text.replace("@@FITNESS@@", _table_for("fitness", language))
    text = text.replace("@@META@@", _table_for("meta", language))
    if language == "c":
        # the quirk block sits inside a /* */ comment in the C template
        text = text.replace(_quirk_lines(comment), "/*\n" + _quirk_lines(comment) + "\n */")
    return {"language": language, "filename": _FILENAMES[language], "source": text}
