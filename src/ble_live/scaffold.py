"""Receiver scaffolds: a self-contained BLE Live decoder skeleton in a target language.

Each scaffold carries the spec's field tables (index, name, size, signedness) generated from
`spec.json`, the DPI/DFD/DFV state machine keyed by device id, the 0xFD header handling with a
decryption hook, and the receiver quirks as comments. Python and C scaffolds are compiled and
run against the golden vectors in the test suite; the C#, Kotlin and Swift ones follow the
same structure but are not compiled here.
"""

from __future__ import annotations

from . import spec

LANGUAGES = ("python", "c", "csharp", "kotlin", "swift")


def _rows(category: str) -> list[tuple[int, str, int, bool]]:
    out = []
    for row in spec.fields(category):
        if row["index"] == 255:
            continue
        size = row.get("size_bytes") or 0  # 0 = variable: array to end of payload
        signed = (row.get("type") or "").startswith("int")
        out.append((row["index"], row["name"], size, signed))
    return out


def _quirk_lines(prefix: str) -> str:
    lines = [f"{prefix} Receiver quirks (see quirks://receivers in the BLE Live MCP server):"]
    for q in spec.load_quirks()["quirks"]:
        lines.append(f"{prefix} - {q['id']}: {q['rule']}")
    return "\n".join(lines)


def _table(category: str, fmt: str) -> str:
    return "\n".join(
        fmt.format(index=i, name=n.replace('"', "'"), size=s, signed=sg)
        for i, n, s, sg in _rows(category)
    )


def _fill(template: str, lang_fmt: dict[str, str], comment: str) -> str:
    text = template.replace("@@VERSION@@", spec.version())
    text = text.replace("@@QUIRKS@@", _quirk_lines(comment))
    text = text.replace("@@FITNESS@@", _table("fitness", lang_fmt["row"]))
    text = text.replace("@@META@@", _table("meta", lang_fmt["row"]))
    return text


